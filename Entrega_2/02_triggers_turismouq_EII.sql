-- 1. Tabla que registra las operaciones efectuadas sobre TARIFA.
-- EJECUCIÓN SEGURA: la tabla ya existe en el entorno trabajado. No ejecutar
-- este CREATE TABLE nuevamente si AUDITORIA_TARIFA ya existe.
-- Si solo se están actualizando triggers, ejecutar desde el apartado 2.
CREATE TABLE AUDITORIA_TARIFA (
    ID_AUDITORIA    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TARIFA       NUMBER,
    ID_HABITACION   NUMBER,
    ID_TEMPORADA    NUMBER,
    OPERACION       VARCHAR2(10) NOT NULL,
    VALOR_ANTERIOR  NUMBER(12,2),
    VALOR_NUEVO     NUMBER(12,2),
    USUARIO_BD      VARCHAR2(128) NOT NULL,
    FECHA_CAMBIO    TIMESTAMP NOT NULL
);

-- 2. Trigger compuesto: captura usuario/hora a nivel de sentencia y registra
-- cada fila afectada. El formato compuesto evita mutating-table al auditar.
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_TARIFA
FOR INSERT OR UPDATE OR DELETE ON TARIFA
COMPOUND TRIGGER
    V_USUARIO VARCHAR2(128);
    V_FECHA   TIMESTAMP;

    BEFORE STATEMENT IS
    BEGIN
        V_USUARIO := SYS_CONTEXT('USERENV', 'SESSION_USER');
        V_FECHA := SYSTIMESTAMP;
    END BEFORE STATEMENT;

    AFTER EACH ROW IS
    BEGIN
        IF INSERTING THEN
            INSERT INTO AUDITORIA_TARIFA (
                ID_TARIFA, ID_HABITACION, ID_TEMPORADA, OPERACION,
                VALOR_ANTERIOR, VALOR_NUEVO, USUARIO_BD, FECHA_CAMBIO
            ) VALUES (
                :NEW.ID_TARIFA, :NEW.ID_HABITACION, :NEW.ID_TEMPORADA,
                'INSERT', NULL, :NEW.VALOR_NOCHE, V_USUARIO, V_FECHA
            );
        ELSIF UPDATING THEN
            INSERT INTO AUDITORIA_TARIFA (
                ID_TARIFA, ID_HABITACION, ID_TEMPORADA, OPERACION,
                VALOR_ANTERIOR, VALOR_NUEVO, USUARIO_BD, FECHA_CAMBIO
            ) VALUES (
                :NEW.ID_TARIFA, :NEW.ID_HABITACION, :NEW.ID_TEMPORADA,
                'UPDATE', :OLD.VALOR_NOCHE, :NEW.VALOR_NOCHE,
                V_USUARIO, V_FECHA
            );
        ELSIF DELETING THEN
            INSERT INTO AUDITORIA_TARIFA (
                ID_TARIFA, ID_HABITACION, ID_TEMPORADA, OPERACION,
                VALOR_ANTERIOR, VALOR_NUEVO, USUARIO_BD, FECHA_CAMBIO
            ) VALUES (
                :OLD.ID_TARIFA, :OLD.ID_HABITACION, :OLD.ID_TEMPORADA,
                'DELETE', :OLD.VALOR_NOCHE, NULL, V_USUARIO, V_FECHA
            );
        END IF;
    END AFTER EACH ROW;
END TRG_AUDITORIA_TARIFA;
/

-- 3. Trigger compuesto de prevención de solapamientos. La comprobación se
-- realiza AFTER STATEMENT para poder consultar RESERVA_HABITACION sin error
-- de tabla mutante. Solo bloquea reservas Pendiente o Confirmada.
CREATE OR REPLACE TRIGGER TRG_EVITAR_SOLAPAMIENTO
FOR INSERT OR UPDATE OF ID_RESERVA, ID_HABITACION, FECHA_CHECKIN, FECHA_CHECKOUT
ON RESERVA_HABITACION
COMPOUND TRIGGER
    TYPE T_FILA IS RECORD (
        ID_RH       RESERVA_HABITACION.ID_RESERVA_HABITACION%TYPE,
        ID_RESERVA  RESERVA_HABITACION.ID_RESERVA%TYPE,
        ID_HAB      RESERVA_HABITACION.ID_HABITACION%TYPE,
        FECHA_IN    RESERVA_HABITACION.FECHA_CHECKIN%TYPE,
        FECHA_OUT   RESERVA_HABITACION.FECHA_CHECKOUT%TYPE
    );
    TYPE T_FILAS IS TABLE OF T_FILA INDEX BY PLS_INTEGER;
    V_FILAS T_FILAS;
    V_N PLS_INTEGER := 0;
    V_CONFLICTOS PLS_INTEGER;

    AFTER EACH ROW IS
    BEGIN
        V_N := V_N + 1;
        V_FILAS(V_N).ID_RH := :NEW.ID_RESERVA_HABITACION;
        V_FILAS(V_N).ID_RESERVA := :NEW.ID_RESERVA;
        V_FILAS(V_N).ID_HAB := :NEW.ID_HABITACION;
        V_FILAS(V_N).FECHA_IN := :NEW.FECHA_CHECKIN;
        V_FILAS(V_N).FECHA_OUT := :NEW.FECHA_CHECKOUT;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        FOR I IN 1 .. V_N LOOP
            SELECT COUNT(*)
            INTO V_CONFLICTOS
            FROM RESERVA_HABITACION RH
            JOIN RESERVA R ON R.ID_RESERVA = RH.ID_RESERVA
            WHERE RH.ID_HABITACION = V_FILAS(I).ID_HAB
              AND RH.ID_RESERVA_HABITACION <> V_FILAS(I).ID_RH
              AND R.ESTADO IN ('Confirmada', 'Pendiente')
              AND RH.FECHA_CHECKIN < V_FILAS(I).FECHA_OUT
              AND RH.FECHA_CHECKOUT > V_FILAS(I).FECHA_IN;

            IF V_CONFLICTOS > 0 THEN
                RAISE_APPLICATION_ERROR(-20016,
                    'La habitacion tiene otra reserva pendiente o confirmada ' ||
                    'que se solapa con el periodo solicitado.');
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END TRG_EVITAR_SOLAPAMIENTO;
/

-- 4. Verificación de los dos triggers.
SELECT TRIGGER_NAME, STATUS, TRIGGERING_EVENT
FROM USER_TRIGGERS
WHERE TRIGGER_NAME IN ('TRG_AUDITORIA_TARIFA', 'TRG_EVITAR_SOLAPAMIENTO')
ORDER BY TRIGGER_NAME;

