/* ========================================================
   1. MUNICIPIO
   Almacena los municipios del departamento del Quindío.
   ======================================================== */

CREATE TABLE MUNICIPIO (
    id_municipio NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR2(100) NOT NULL,

    CONSTRAINT PK_MUNICIPIO
        PRIMARY KEY (id_municipio),

    CONSTRAINT UQ_MUNICIPIO_NOMBRE
        UNIQUE (nombre)
);


/* ========================================================
   2. TIPO_ALOJAMIENTO
   Tipos de alojamiento ofrecidos por TurismoUQ.
   ======================================================== */

CREATE TABLE TIPO_ALOJAMIENTO (
    id_tipo     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR2(50) NOT NULL,
    descripcion VARCHAR2(500),

    CONSTRAINT PK_TIPO_ALOJAMIENTO
        PRIMARY KEY (id_tipo),

    CONSTRAINT UQ_TIPO_ALOJAMIENTO_NOMBRE
        UNIQUE (nombre)
);


/* ========================================================
   3. ALOJAMIENTO
   Información de hoteles, fincas cafeteras, glampings,
   hostales y otros tipos de alojamiento.
   ======================================================== */

CREATE TABLE ALOJAMIENTO (
    id_alojamiento NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_municipio   NUMBER(10) NOT NULL,
    id_tipo        NUMBER(10) NOT NULL,
    nombre         VARCHAR2(150) NOT NULL,
    direccion      VARCHAR2(250) NOT NULL,
    estrellas      NUMBER(1) NOT NULL,
    telefono       VARCHAR2(20),
    correo         VARCHAR2(150),

    CONSTRAINT PK_ALOJAMIENTO
        PRIMARY KEY (id_alojamiento),

    CONSTRAINT FK_ALOJAMIENTO_MUNICIPIO
        FOREIGN KEY (id_municipio)
        REFERENCES MUNICIPIO(id_municipio),

    CONSTRAINT FK_ALOJAMIENTO_TIPO
        FOREIGN KEY (id_tipo)
        REFERENCES TIPO_ALOJAMIENTO(id_tipo),

    CONSTRAINT CK_ALOJAMIENTO_ESTRELLAS
        CHECK (estrellas BETWEEN 1 AND 5)
);


/* ========================================================
   4. HABITACION
   Habitaciones o unidades disponibles en cada alojamiento.
   ======================================================== */

CREATE TABLE HABITACION (
    id_habitacion  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(10) NOT NULL,
    numero         VARCHAR2(20) NOT NULL,
    capacidad      NUMBER(3) NOT NULL,
    tipo           VARCHAR2(50) NOT NULL,
    descripcion    VARCHAR2(500),

    CONSTRAINT PK_HABITACION
        PRIMARY KEY (id_habitacion),

    CONSTRAINT FK_HABITACION_ALOJAMIENTO
        FOREIGN KEY (id_alojamiento)
        REFERENCES ALOJAMIENTO(id_alojamiento),

    CONSTRAINT UQ_HABITACION_ALOJAMIENTO_NUMERO
        UNIQUE (id_alojamiento, numero),

    CONSTRAINT CK_HABITACION_CAPACIDAD
        CHECK (capacidad > 0)
);


/* ========================================================
   5. TEMPORADA
   Periodos de temporada alta, media o baja.
   ======================================================== */

CREATE TABLE TEMPORADA (
    id_temporada NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR2(100) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin    DATE NOT NULL,
    anio         NUMBER(4) NOT NULL,
    columna_6    VARCHAR2(100),

    CONSTRAINT PK_TEMPORADA
        PRIMARY KEY (id_temporada),

    CONSTRAINT CK_TEMPORADA_FECHAS
        CHECK (fecha_fin >= fecha_inicio),

    CONSTRAINT CK_TEMPORADA_ANIO
        CHECK (anio BETWEEN 2020 AND 2100)
);


/* ========================================================
   6. TARIFA
   Define el precio por noche de una habitación para
   una temporada determinada.
   ======================================================== */

CREATE TABLE TARIFA (
    id_tarifa      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_habitacion  NUMBER(10) NOT NULL,
    id_temporada   NUMBER(10) NOT NULL,
    valor_noche    NUMBER(12,2) NOT NULL,

    CONSTRAINT PK_TARIFA
        PRIMARY KEY (id_tarifa),

    CONSTRAINT FK_TARIFA_HABITACION
        FOREIGN KEY (id_habitacion)
        REFERENCES HABITACION(id_habitacion),

    CONSTRAINT FK_TARIFA_TEMPORADA
        FOREIGN KEY (id_temporada)
        REFERENCES TEMPORADA(id_temporada),

    CONSTRAINT UQ_TARIFA_HABITACION_TEMPORADA
        UNIQUE (id_habitacion, id_temporada),

    CONSTRAINT CK_TARIFA_VALOR
        CHECK (valor_noche > 0)
);


/* ========================================================
   7. CLIENTE
   Personas que realizan reservas en TurismoUQ.
   ======================================================== */

CREATE TABLE CLIENTE (
    id_cliente     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    documento      VARCHAR2(30) NOT NULL,
    nombre         VARCHAR2(150) NOT NULL,
    correo         VARCHAR2(150) NOT NULL,
    telefono       VARCHAR2(20),
    ciudad_origen  VARCHAR2(100) NOT NULL,

    CONSTRAINT PK_CLIENTE
        PRIMARY KEY (id_cliente),

    CONSTRAINT UQ_CLIENTE_DOCUMENTO
        UNIQUE (documento),

    CONSTRAINT UQ_CLIENTE_CORREO
        UNIQUE (correo)
);


/* ========================================================
   8. RESERVA
   Reserva realizada por un cliente.
   ======================================================== */

CREATE TABLE RESERVA (
    id_reserva      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_cliente      NUMBER(10) NOT NULL,
    fecha_checkin   DATE NOT NULL,
    fecha_checkout  DATE NOT NULL,
    estado          VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_RESERVA
        PRIMARY KEY (id_reserva),

    CONSTRAINT FK_RESERVA_CLIENTE
        FOREIGN KEY (id_cliente)
        REFERENCES CLIENTE(id_cliente),

    CONSTRAINT CK_RESERVA_FECHAS
        CHECK (fecha_checkout > fecha_checkin),

    CONSTRAINT CK_RESERVA_ESTADO
        CHECK (
            estado IN (
                'Pendiente',
                'Confirmada',
                'Cancelada',
                'Completada'
            )
        )
);


/* ========================================================
   9. RESERVA_HABITACION
   Relación entre reservas y habitaciones.
   Permite que una reserva tenga varias habitaciones y
   que cada habitación tenga sus propias fechas.
   ======================================================== */

CREATE TABLE RESERVA_HABITACION (
    id_reserva_habitacion NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_reserva             NUMBER(10) NOT NULL,
    id_habitacion          NUMBER(10) NOT NULL,
    fecha_checkin          DATE NOT NULL,
    fecha_checkout         DATE NOT NULL,
    cantidad_huespedes     NUMBER(3) NOT NULL,

    CONSTRAINT PK_RESERVA_HABITACION
        PRIMARY KEY (id_reserva_habitacion),

    CONSTRAINT FK_RESERVA_HABITACION_RESERVA
        FOREIGN KEY (id_reserva)
        REFERENCES RESERVA(id_reserva),

    CONSTRAINT FK_RESERVA_HABITACION_HABITACION
        FOREIGN KEY (id_habitacion)
        REFERENCES HABITACION(id_habitacion),

    CONSTRAINT CK_RESERVA_HABITACION_FECHAS
        CHECK (fecha_checkout > fecha_checkin),

    CONSTRAINT CK_RESERVA_HABITACION_HUESPEDES
        CHECK (cantidad_huespedes > 0)
);


/* ========================================================
   10. PAGO
   Pagos realizados para una reserva.
   Una reserva puede tener varios pagos.
   ======================================================== */

CREATE TABLE PAGO (
    id_pago     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_reserva  NUMBER(10) NOT NULL,
    fecha_pago  DATE NOT NULL,
    monto       NUMBER(12,2) NOT NULL,
    metodo      VARCHAR2(30) NOT NULL,
    estado      VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_PAGO
        PRIMARY KEY (id_pago),

    CONSTRAINT FK_PAGO_RESERVA
        FOREIGN KEY (id_reserva)
        REFERENCES RESERVA(id_reserva),

    CONSTRAINT CK_PAGO_MONTO
        CHECK (monto > 0),

    CONSTRAINT CK_PAGO_METODO
        CHECK (
            metodo IN (
                'Tarjeta de credito',
                'Tarjeta debito',
                'PSE',
                'Transferencia',
                'Efectivo'
            )
        ),

    CONSTRAINT CK_PAGO_ESTADO
        CHECK (
            estado IN (
                'Exitoso',
                'Fallido',
                'Pendiente',
                'Reembolsado'
            )
        )
);


/* ========================================================
   11. SERVICIO
   Servicios complementarios ofrecidos por cada alojamiento.
   ======================================================== */

CREATE TABLE SERVICIO (
    id_servicio    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(10) NOT NULL,
    nombre         VARCHAR2(100) NOT NULL,
    descripcion    VARCHAR2(500),
    precio         NUMBER(12,2) NOT NULL,

    CONSTRAINT PK_SERVICIO
        PRIMARY KEY (id_servicio),

    CONSTRAINT FK_SERVICIO_ALOJAMIENTO
        FOREIGN KEY (id_alojamiento)
        REFERENCES ALOJAMIENTO(id_alojamiento),

    CONSTRAINT CK_SERVICIO_PRECIO
        CHECK (precio > 0)
);


/* ========================================================
   12. RESERVA_SERVICIO
   Relación entre reservas y servicios.
   Permite solicitar varias unidades de un mismo servicio.
   ======================================================== */

CREATE TABLE RESERVA_SERVICIO (
    id_reserva_servicio NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_reserva          NUMBER(10) NOT NULL,
    id_servicio         NUMBER(10) NOT NULL,
    cantidad            NUMBER(5) NOT NULL,
    precio_unitario     NUMBER(12,2) NOT NULL,

    CONSTRAINT PK_RESERVA_SERVICIO
        PRIMARY KEY (id_reserva_servicio),

    CONSTRAINT FK_RESERVA_SERVICIO_RESERVA
        FOREIGN KEY (id_reserva)
        REFERENCES RESERVA(id_reserva),

    CONSTRAINT FK_RESERVA_SERVICIO_SERVICIO
        FOREIGN KEY (id_servicio)
        REFERENCES SERVICIO(id_servicio),

    CONSTRAINT CK_RESERVA_SERVICIO_CANTIDAD
        CHECK (cantidad > 0),

    CONSTRAINT CK_RESERVA_SERVICIO_PRECIO
        CHECK (precio_unitario > 0)
);


/* ========================================================
   13. RESENA
   Reseñas realizadas por clientes sobre alojamientos.
   ======================================================== */

CREATE TABLE RESENA (
    id_resena      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_cliente     NUMBER(10) NOT NULL,
    id_alojamiento NUMBER(10) NOT NULL,
    calificacion   NUMBER(1) NOT NULL,
    comentario     VARCHAR2(1000),
    fecha_resena   DATE NOT NULL,

    CONSTRAINT PK_RESENA
        PRIMARY KEY (id_resena),

    CONSTRAINT FK_RESENA_CLIENTE
        FOREIGN KEY (id_cliente)
        REFERENCES CLIENTE(id_cliente),

    CONSTRAINT FK_RESENA_ALOJAMIENTO
        FOREIGN KEY (id_alojamiento)
        REFERENCES ALOJAMIENTO(id_alojamiento),

    CONSTRAINT CK_RESENA_CALIFICACION
        CHECK (calificacion BETWEEN 1 AND 5)
);


/* ========================================================
   14. USUARIO_SISTEMA
   Usuarios internos de TurismoUQ.
   Los administradores pueden pertenecer a la plataforma,
   mientras que los encargados pueden asociarse a un
   alojamiento específico.
   ======================================================== */

CREATE TABLE USUARIO_SISTEMA (
    id_usuario     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(10),
    nombre_usuario VARCHAR2(50) NOT NULL,
    nombre_completo VARCHAR2(150) NOT NULL,
    correo         VARCHAR2(150) NOT NULL,
    rol            VARCHAR2(30) NOT NULL,
    estado         VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_USUARIO_SISTEMA
        PRIMARY KEY (id_usuario),

    CONSTRAINT FK_USUARIO_ALOJAMIENTO
        FOREIGN KEY (id_alojamiento)
        REFERENCES ALOJAMIENTO(id_alojamiento),

    CONSTRAINT UQ_USUARIO_NOMBRE
        UNIQUE (nombre_usuario),

    CONSTRAINT UQ_USUARIO_CORREO
        UNIQUE (correo),

    CONSTRAINT CK_USUARIO_ROL
        CHECK (
            rol IN (
                'Administrador',
                'Encargado'
            )
        ),

    CONSTRAINT CK_USUARIO_ESTADO
        CHECK (
            estado IN (
                'Activo',
                'Inactivo'
            )
        )
);


